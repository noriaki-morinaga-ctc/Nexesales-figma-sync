//
// 候補の求め方は 2 通りあり、引数 targetMonth の有無で切り替わる。
//   ・targetMonth あり：その対象年月の**支払として実在する組合せ**のみを候補にする
//     （memo A「候補は分割元と同じ対象年月の支払を参照する」。振替詳細が使用）
