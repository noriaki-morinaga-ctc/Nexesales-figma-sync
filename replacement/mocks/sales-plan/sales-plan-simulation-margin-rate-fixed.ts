// 作成者のダミー割り当てに使う決定的なハッシュ。
export const hashId = (id?: string): number => {
  const s = String(id ?? '');
  let h = 0;
  for (let i = 0; i < s.length; i += 1) h = (h * 31 + s.charCodeAt(i)) | 0;
  return Math.abs(h);
};

