export const seedCreator = (
  d: Record<string, string | undefined>,
  prefix: 'exp1' | 'exp2'
): void => {
  if (d[`${prefix}Creator`] !== undefined) return;
  d[`${prefix}Creator`] = d[`${prefix}PlannedAmount`]
    ? SIM_CREATORS[hashId(d.id) % SIM_CREATORS.length]
    : '';
};
